"use client";
import { useState, useEffect } from "react";
import { useParams, useRouter } from "next/navigation";
import { motion } from "framer-motion";
import { ArrowLeft, CheckCircle2, AlertCircle, Share2, Download, RefreshCcw, Eye, Check } from "lucide-react";
import { submissionsApi } from "@/lib/api";
import ReasoningTrace from "@/components/visualization/ReasoningTrace";
import Link from "next/link";

export default function ResultsPage() {
  const { id } = useParams();
  const router = useRouter();
  const [data, setData] = useState<any>(null);
  const [loading, setLoading] = useState(true);
  const [shareSuccess, setShareSuccess] = useState(false);

  useEffect(() => {
    async function loadResult() {
      try {
        const res = await submissionsApi.get(id as string);
        setData(res.data);
      } catch (err) {
        console.error("Failed to load result", err);
      } finally {
        setLoading(false);
      }
    }
    if (id) loadResult();
  }, [id]);

  // Extract feedback text from either string or {message: string} format
  const getFeedback = (fb: any): string => {
    if (!fb) return "Evaluation complete.";
    if (typeof fb === "string") return fb;
    if (typeof fb === "object" && fb.message) return fb.message;
    return JSON.stringify(fb);
  };

  // Share: copy result summary to clipboard
  const handleShare = async () => {
    if (!data) return;
    const summary = `RIMN Assessment Result\n` +
      `Score: ${data.score?.toFixed?.(0) ?? data.score}/100\n` +
      `Subject: ${data.subject || "General"}\n` +
      `Topic: ${data.topic || "N/A"}\n` +
      `Confidence: ${((data.confidence || 0) * 100).toFixed(0)}%\n` +
      `Status: ${data.status}\n\n` +
      `Feedback:\n${getFeedback(data.feedback)}\n\n` +
      `— Graded by RIMN Multimodal Engine`;
    
    try {
      await navigator.clipboard.writeText(summary);
      setShareSuccess(true);
      setTimeout(() => setShareSuccess(false), 2000);
    } catch {
      // Fallback for older browsers
      const el = document.createElement("textarea");
      el.value = summary;
      document.body.appendChild(el);
      el.select();
      document.execCommand("copy");
      document.body.removeChild(el);
      setShareSuccess(true);
      setTimeout(() => setShareSuccess(false), 2000);
    }
  };

  // Download: generate a text report as downloadable file
  const handleDownload = () => {
    if (!data) return;
    const report = [
      "═══════════════════════════════════════════════════",
      "              RIMN ASSESSMENT REPORT",
      "     Recursive Iterative Modality Negotiation",
      "═══════════════════════════════════════════════════",
      "",
      `Submission ID: ${data.id || id}`,
      `Date: ${data.created_at || new Date().toISOString()}`,
      `Subject: ${data.subject || "General"}`,
      `Topic: ${data.topic || "N/A"}`,
      "",
      "───────────────────────────────────────────────────",
      "  SCORE & METRICS",
      "───────────────────────────────────────────────────",
      `  Score:      ${data.score?.toFixed?.(1) ?? data.score} / 100`,
      `  Confidence: ${((data.confidence || 0) * 100).toFixed(0)}%`,
      `  Status:     ${data.status || "done"}`,
      `  Contradiction: ${data.contradiction_detected ? "YES ⚠️" : "None detected"}`,
      "",
      "───────────────────────────────────────────────────",
      "  QUESTION",
      "───────────────────────────────────────────────────",
      `  ${data.question || "N/A"}`,
      "",
      "───────────────────────────────────────────────────",
      "  STUDENT ANSWER",
      "───────────────────────────────────────────────────",
      `  ${data.student_answer || "N/A"}`,
      "",
      "───────────────────────────────────────────────────",
      "  AI FEEDBACK",
      "───────────────────────────────────────────────────",
      `  ${getFeedback(data.feedback)}`,
      "",
      "───────────────────────────────────────────────────",
      "  REASONING TRACE",
      "───────────────────────────────────────────────────",
      ...(data.reasoning_trace || []).map((step: any, i: number) =>
        `  Step ${i + 1}: ${step.label || step.title || step.description || "Analysis"} — ${step.message || step.description || "Processed"}`
      ),
      "",
      "═══════════════════════════════════════════════════",
      "  Generated by RIMN Multimodal Engine",
      "═══════════════════════════════════════════════════",
    ].join("\n");

    const blob = new Blob([report], { type: "text/plain;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `RIMN_Report_${(id as string)?.slice(0, 8) || "result"}.txt`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  if (loading) {
    return (
      <div className="min-h-screen bg-[#0A0A0F] flex flex-col items-center justify-center gap-6">
        <div className="w-16 h-16 border-4 border-indigo-500/30 border-t-indigo-500 rounded-full animate-spin" />
        <p className="text-slate-400 font-outfit animate-pulse">Negotiating Modal Representations...</p>
      </div>
    );
  }

  if (!data) return <div className="p-20 text-center">Result not found.</div>;

  const score = typeof data.score === "number" ? data.score : parseFloat(data.score) || 0;
  const confidence = typeof data.confidence === "number" ? data.confidence : parseFloat(data.confidence) || 0;
  const feedbackText = getFeedback(data.feedback);

  return (
    <div className="min-h-screen bg-[#0A0A0F] p-8">
      <div className="max-w-6xl mx-auto">
        <header className="flex items-center justify-between mb-10">
          <div className="flex items-center gap-6">
            <Link href="/student/history" className="p-3 glass rounded-xl hover:bg-white/10 transition-all text-slate-400 hover:text-white">
              <ArrowLeft className="w-6 h-6" />
            </Link>
            <div>
              <div className="flex items-center gap-3 mb-1">
                <h1 className="text-3xl font-black font-outfit">Analysis Results</h1>
                <span className="badge badge-violet">ID: {(id as string)?.slice(0, 8)}</span>
              </div>
              <p className="text-slate-500">Graded by RIMN Multimodal Engine</p>
            </div>
          </div>
          <div className="flex items-center gap-3">
            <button onClick={handleShare} className="btn-ghost p-3 rounded-xl relative group" title="Copy to clipboard">
              {shareSuccess ? <Check className="w-5 h-5 text-emerald-400" /> : <Share2 className="w-5 h-5" />}
              {shareSuccess && (
                <span className="absolute -bottom-8 left-1/2 -translate-x-1/2 text-[10px] font-bold text-emerald-400 whitespace-nowrap">
                  Copied!
                </span>
              )}
            </button>
            <button onClick={handleDownload} className="btn-ghost p-3 rounded-xl" title="Download report">
              <Download className="w-5 h-5" />
            </button>
            <button onClick={() => router.push('/student/submit')} className="btn-primary flex items-center gap-2">
              <RefreshCcw className="w-4 h-4" /> Try Another
            </button>
          </div>
        </header>

        <div className="grid grid-cols-1 lg:grid-cols-12 gap-8">
          {/* Left Column: Summary */}
          <div className="lg:col-span-4 space-y-8">
            {/* Score Card */}
            <div className="glass p-8 relative overflow-hidden flex flex-col items-center text-center">
              <div className="absolute top-0 right-0 p-4">
                {score >= 70 ? <CheckCircle2 className="w-8 h-8 text-green-500/50" /> : <AlertCircle className="w-8 h-8 text-amber-500/50" />}
              </div>
              
              <div className="w-32 h-32 rounded-full border-8 border-white/5 flex flex-col items-center justify-center mb-6 relative">
                <svg className="absolute inset-0 w-full h-full -rotate-90">
                  <circle 
                    cx="64" cy="64" r="56" 
                    fill="transparent" 
                    stroke="currentColor" 
                    strokeWidth="8"
                    className="text-indigo-500/20"
                  />
                  <circle 
                    cx="64" cy="64" r="56" 
                    fill="transparent" 
                    stroke="currentColor" 
                    strokeWidth="8"
                    strokeDasharray={351.8}
                    strokeDashoffset={351.8 - (351.8 * score) / 100}
                    strokeLinecap="round"
                    className="text-indigo-500"
                  />
                </svg>
                <span className="text-4xl font-black font-outfit">{score.toFixed(0)}</span>
                <span className="text-xs font-bold text-slate-500 uppercase">Score</span>
              </div>

              <h2 className="text-2xl font-bold font-outfit mb-2">
                {score >= 85 ? "Excellent Work!" : score >= 70 ? "Well Done" : "Keep Learning"}
              </h2>
              <p className="text-slate-400 text-sm leading-relaxed mb-6">{feedbackText}</p>
              
              <div className="w-full grid grid-cols-2 gap-4 pt-6 border-t border-white/5">
                <div className="text-center">
                  <p className="text-[10px] font-bold text-slate-500 uppercase tracking-widest mb-1">Confidence</p>
                  <p className="font-bold text-slate-200">{(confidence * 100).toFixed(0)}%</p>
                </div>
                <div className="text-center">
                  <p className="text-[10px] font-bold text-slate-500 uppercase tracking-widest mb-1">Status</p>
                  <p className="font-bold text-green-400 capitalize">{data.status}</p>
                </div>
              </div>
            </div>

            {/* Input Preview */}
            <div className="glass p-6 space-y-4">
              <h3 className="font-bold font-outfit text-lg">Input Preview</h3>
              <div className="space-y-3">
                <div className="bg-white/5 p-4 rounded-xl">
                  <p className="text-[10px] font-bold text-slate-500 uppercase tracking-widest mb-2">Question</p>
                  <p className="text-sm text-slate-300 line-clamp-3 italic">"{data.question}"</p>
                </div>
                <div className="bg-white/5 p-4 rounded-xl">
                  <p className="text-[10px] font-bold text-slate-500 uppercase tracking-widest mb-2">Your Answer</p>
                  <p className="text-sm text-slate-300 line-clamp-4 italic">"{data.student_answer}"</p>
                </div>
                {data.contradiction_detected && (
                  <div className="bg-red-500/10 border border-red-500/20 p-4 rounded-xl flex gap-3">
                    <AlertCircle className="w-5 h-5 text-red-400 shrink-0" />
                    <div>
                      <p className="text-xs font-bold text-red-400 uppercase tracking-widest mb-1">Contradiction Warning</p>
                      <p className="text-xs text-slate-400 leading-relaxed">Model detected logical mismatch between text and vision.</p>
                    </div>
                  </div>
                )}
              </div>
            </div>
          </div>

          {/* Right Column: Detailed Analysis */}
          <div className="lg:col-span-8 space-y-8">
            <div className="flex items-center gap-4 mb-2">
              <h3 className="text-2xl font-black font-outfit">Reasoning Trace</h3>
              <div className="h-px flex-1 bg-white/5" />
              <button className="btn-ghost text-xs flex items-center gap-2 py-1 px-3">
                <Eye className="w-3 h-3" /> Technical View
              </button>
            </div>

            <ReasoningTrace trace={data.reasoning_trace || []} currentStep={(data.reasoning_trace || []).length} />

            {/* Evaluation Meta */}
            {data.evaluation_summary && (
              <div className="glass p-6 space-y-3">
                <h3 className="font-bold font-outfit text-lg">Evaluation Summary</h3>
                <p className="text-sm text-slate-400 leading-relaxed">{data.evaluation_summary}</p>
              </div>
            )}
          </div>
        </div>
      </div>
    </div>
  );
}

